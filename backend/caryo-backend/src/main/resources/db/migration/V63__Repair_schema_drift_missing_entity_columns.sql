-- ============================================================================
-- V63: Repair schema drift — objects the entity model expects but no
--      migration ever created
--
-- Two causes, discovered by the application-boot smoke test (which boots the
-- full context on a Flyway-only database with ddl-auto=validate, exactly as
-- production does):
--
--   1. V51 was written without newlines: every `--` comment ran to the end
--      of the single line and swallowed the statements after it, so Flyway
--      recorded it as applied while executing NOTHING. All dealer
--      trial/subscription columns therefore exist only where Hibernate's
--      ddl-auto=update silently created them (the dev stack).
--      V51 is immutable history and its checksum is already recorded, so the
--      repair lands here instead of editing it.
--
--   2. Several features (listing contact fields, car trims, password reset,
--      translations, governorate geo fields) added entities without a
--      migration; dev's ddl-auto=update masked the gap.
--
-- Every statement is guarded (IF NOT EXISTS / WHERE ... IS NULL): on the dev
-- database these objects already exist, on a fresh production database none
-- of them do. Column types mirror the entity mappings exactly (verified
-- against the Hibernate-generated dev schema), so ddl-auto=validate passes.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. dealers — trial and subscription fields (V51's lost payload)
--    notifications_sent is TEXT, not JSONB: the entity maps it as
--    @Column(columnDefinition = "text") with a converter.
-- ----------------------------------------------------------------------------
ALTER TABLE dealers
    ADD COLUMN IF NOT EXISTS trial_started_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS trial_listings_count INTEGER DEFAULT 0 NOT NULL,
    ADD COLUMN IF NOT EXISTS trial_expired BOOLEAN DEFAULT FALSE NOT NULL,
    ADD COLUMN IF NOT EXISTS trial_extended_until TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS timezone VARCHAR(50) DEFAULT 'Asia/Damascus',
    ADD COLUMN IF NOT EXISTS subscription_tier VARCHAR(50) DEFAULT 'trial',
    ADD COLUMN IF NOT EXISTS subscription_started_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS subscription_status VARCHAR(50) DEFAULT 'trial',
    ADD COLUMN IF NOT EXISTS subscription_next_billing_date TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS subscription_cancelled_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS notifications_sent TEXT DEFAULT '[]',
    ADD COLUMN IF NOT EXISTS can_create_listings BOOLEAN DEFAULT TRUE NOT NULL,
    ADD COLUMN IF NOT EXISTS payment_warning BOOLEAN DEFAULT FALSE NOT NULL;

CREATE INDEX IF NOT EXISTS idx_dealers_trial_expired ON dealers(trial_expired) WHERE trial_expired = false;
CREATE INDEX IF NOT EXISTS idx_dealers_subscription_tier ON dealers(subscription_tier);
CREATE INDEX IF NOT EXISTS idx_dealers_subscription_status ON dealers(subscription_status);
CREATE INDEX IF NOT EXISTS idx_dealers_trial_started_at ON dealers(trial_started_at);

UPDATE dealers SET trial_started_at = created_at WHERE trial_started_at IS NULL;
UPDATE dealers SET notifications_sent = '[]' WHERE notifications_sent IS NULL;

-- ----------------------------------------------------------------------------
-- 2. car_listings — seller contact fields
-- ----------------------------------------------------------------------------
ALTER TABLE car_listings
    ADD COLUMN IF NOT EXISTS contact_name VARCHAR(100),
    ADD COLUMN IF NOT EXISTS contact_phone VARCHAR(50),
    ADD COLUMN IF NOT EXISTS contact_email VARCHAR(255),
    ADD COLUMN IF NOT EXISTS contact_preference VARCHAR(20) DEFAULT 'email';

-- ----------------------------------------------------------------------------
-- 3. governorates — geo fields
-- ----------------------------------------------------------------------------
ALTER TABLE governorates
    ADD COLUMN IF NOT EXISTS latitude DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS longitude DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS region VARCHAR(100);

-- ----------------------------------------------------------------------------
-- 4. car_trims — trim catalog per model
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS car_trims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    display_name_en VARCHAR(100) NOT NULL,
    display_name_ar VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL,
    model_id BIGINT NOT NULL,
    CONSTRAINT fk_car_trims_model FOREIGN KEY (model_id) REFERENCES models(id)
);

-- ----------------------------------------------------------------------------
-- 5. password_reset_tokens
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(255) NOT NULL,
    user_id BIGINT NOT NULL,
    expiry_date TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    used BOOLEAN NOT NULL,
    CONSTRAINT uq_password_reset_tokens_token UNIQUE (token),
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users(id)
);

-- ----------------------------------------------------------------------------
-- 6. translations — bilingual content translation store
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS translations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(50) NOT NULL,
    entity_id BIGINT NOT NULL,
    language_code VARCHAR(5) NOT NULL,
    field_name VARCHAR(100) NOT NULL,
    source_text TEXT NOT NULL,
    translated_text TEXT NOT NULL,
    translation_source VARCHAR(20) NOT NULL,
    confidence_score DOUBLE PRECISION NOT NULL,
    is_verified BOOLEAN NOT NULL,
    is_active BOOLEAN NOT NULL,
    last_modified TIMESTAMP(6),
    last_modified_by VARCHAR(255),
    CONSTRAINT uq_translations_entity_lang_field UNIQUE (entity_type, entity_id, language_code, field_name)
);

-- ----------------------------------------------------------------------------
-- 7. Type corrections — columns whose migration-era type no longer matches
--    the entity mapping (ddl-auto=validate rejects these on boot).
--    Each ALTER is guarded on the column's CURRENT type, so the block is a
--    no-op on databases that have already converged.
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    -- Entity maps governorate_id as Long (all other FK ids are bigint).
    IF (SELECT udt_name FROM information_schema.columns
        WHERE table_name = 'car_listings' AND column_name = 'governorate_id') = 'int4' THEN
        ALTER TABLE car_listings ALTER COLUMN governorate_id TYPE BIGINT;
    END IF;

    -- Entity maps Role.id as Integer. Narrowing int8 -> int4 is safe here:
    -- roles holds a handful of seed rows with single-digit ids. The FK has
    -- to be dropped around the change and re-created.
    IF (SELECT udt_name FROM information_schema.columns
        WHERE table_name = 'roles' AND column_name = 'id') = 'int8' THEN
        ALTER TABLE user_roles DROP CONSTRAINT IF EXISTS user_roles_role_id_fkey;
        ALTER TABLE roles ALTER COLUMN id TYPE INTEGER;
        ALTER TABLE user_roles ALTER COLUMN role_id TYPE INTEGER;
        ALTER TABLE user_roles ADD CONSTRAINT user_roles_role_id_fkey
            FOREIGN KEY (role_id) REFERENCES roles(id);
    END IF;

    -- Entities map created_at/updated_at as ZonedDateTime (timestamptz).
    -- Stored values were written as UTC, so reinterpret rather than shift.
    IF (SELECT udt_name FROM information_schema.columns
        WHERE table_name = 'countries' AND column_name = 'created_at') = 'timestamp' THEN
        ALTER TABLE countries
            ALTER COLUMN created_at TYPE TIMESTAMP WITH TIME ZONE USING created_at AT TIME ZONE 'UTC',
            ALTER COLUMN updated_at TYPE TIMESTAMP WITH TIME ZONE USING updated_at AT TIME ZONE 'UTC';
    END IF;
    IF (SELECT udt_name FROM information_schema.columns
        WHERE table_name = 'governorates' AND column_name = 'created_at') = 'timestamp' THEN
        ALTER TABLE governorates
            ALTER COLUMN created_at TYPE TIMESTAMP WITH TIME ZONE USING created_at AT TIME ZONE 'UTC',
            ALTER COLUMN updated_at TYPE TIMESTAMP WITH TIME ZONE USING updated_at AT TIME ZONE 'UTC';
    END IF;
    IF (SELECT udt_name FROM information_schema.columns
        WHERE table_name = 'locations' AND column_name = 'created_at') = 'timestamp' THEN
        ALTER TABLE locations
            ALTER COLUMN created_at TYPE TIMESTAMP WITH TIME ZONE USING created_at AT TIME ZONE 'UTC',
            ALTER COLUMN updated_at TYPE TIMESTAMP WITH TIME ZONE USING updated_at AT TIME ZONE 'UTC';
    END IF;

    -- Entity maps coordinates as Double (numeric(10,8)/(11,8) -> float8).
    IF (SELECT udt_name FROM information_schema.columns
        WHERE table_name = 'locations' AND column_name = 'latitude') = 'numeric' THEN
        ALTER TABLE locations
            ALTER COLUMN latitude TYPE DOUBLE PRECISION,
            ALTER COLUMN longitude TYPE DOUBLE PRECISION;
    END IF;
END $$;

